-- EXPAND. Novas estruturas privadas; nenhuma promoção ou backfill de contas.
-- USER é o acesso padrão implícito. ADMIN é global; MODERATOR é por comunidade.
CREATE TABLE IF NOT EXISTS soe_private.platform_admin (
    profile_id uuid PRIMARY KEY REFERENCES public.profile(id),
    granted_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS soe_private.community_moderator (
    profile_id uuid NOT NULL REFERENCES public.profile(id),
    community_id bigint NOT NULL REFERENCES public.community(id),
    assigned_by uuid NOT NULL REFERENCES public.profile(id),
    assigned_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(profile_id, community_id)
);
CREATE INDEX IF NOT EXISTS soe_moderator_community_idx
    ON soe_private.community_moderator(community_id, profile_id);
CREATE TABLE IF NOT EXISTS soe_private.security_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_profile_id uuid REFERENCES public.profile(id),
    database_actor name NOT NULL DEFAULT session_user,
    action text NOT NULL CHECK(action IN ('BOOTSTRAP_ADMIN','ADMIN_GRANTED','ADMIN_REVOKED',
        'MODERATOR_GRANTED','MODERATOR_REVOKED','DISPUTE_RESOLVED')),
    target_profile_id uuid REFERENCES public.profile(id),
    community_id bigint REFERENCES public.community(id),
    match_id bigint REFERENCES public.game_match(id),
    previous_value jsonb NOT NULL,
    next_value jsonb NOT NULL,
    reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 10 AND 2000),
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS soe_audit_match_idx ON soe_private.security_audit(match_id, id);

-- Nenhuma política cliente: default deny. Somente capacidades verificadas abaixo.
ALTER TABLE soe_private.platform_admin ENABLE ROW LEVEL SECURITY;
ALTER TABLE soe_private.community_moderator ENABLE ROW LEVEL SECURITY;
ALTER TABLE soe_private.security_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON soe_private.platform_admin, soe_private.community_moderator,
    soe_private.security_audit FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION soe_private.reject_audit_mutation()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    RAISE EXCEPTION 'SOE_AUDIT_IMMUTABLE' USING ERRCODE='42501';
END;
$$;
DO $$ BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='soe_audit_immutable'
        AND tgrelid='soe_private.security_audit'::regclass) THEN
        CREATE TRIGGER soe_audit_immutable BEFORE UPDATE OR DELETE ON soe_private.security_audit
        FOR EACH ROW EXECUTE FUNCTION soe_private.reject_audit_mutation();
    END IF;
END $$;

CREATE OR REPLACE FUNCTION soe_private.permission_data(p_actor uuid)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
SELECT jsonb_build_object(
    'role',CASE WHEN EXISTS(SELECT 1 FROM soe_private.platform_admin WHERE profile_id=p_actor) THEN 'ADMIN'
        WHEN EXISTS(SELECT 1 FROM soe_private.community_moderator WHERE profile_id=p_actor) THEN 'MODERATOR'
        ELSE 'USER' END,
    'moderated_community_ids',coalesce((SELECT jsonb_agg(community_id ORDER BY community_id)
        FROM soe_private.community_moderator WHERE profile_id=p_actor),'[]'::jsonb));
$$;

CREATE OR REPLACE FUNCTION soe_private.authorize(p_actor uuid,p_community bigint DEFAULT NULL,p_admin_only boolean DEFAULT false)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    -- Leituras/decisões compartilham o lock; concessão/revogação usa lock exclusivo.
    -- Uma revogação concluída é observada pela próxima autorização, sem claims em cache.
    IF current_setting('transaction_isolation') <> 'read committed' THEN
        RAISE EXCEPTION 'SOE_RETRY_TRANSACTION' USING ERRCODE='40001';
    END IF;
    PERFORM pg_advisory_xact_lock_shared(hashtextextended('soe/permissions',0));
    PERFORM soe_private.assert_actor(p_actor);
    IF EXISTS(SELECT 1 FROM soe_private.platform_admin WHERE profile_id=p_actor) THEN RETURN; END IF;
    IF NOT p_admin_only AND EXISTS(SELECT 1 FROM soe_private.community_moderator
        WHERE profile_id=p_actor AND (p_community IS NULL OR community_id=p_community)) THEN RETURN; END IF;
    RAISE EXCEPTION 'SOE_ACCESS_DENIED' USING ERRCODE='42501';
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_identity(p_actor uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE identity jsonb;
BEGIN
    IF NOT EXISTS(SELECT 1 FROM public.profile WHERE id=p_actor) THEN
        RETURN jsonb_build_object('id',p_actor,'username','','player_id',NULL,
            'needs_profile',true,'role','USER','moderated_community_ids','[]'::jsonb);
    END IF;
    PERFORM soe_private.assert_actor(p_actor);
    SELECT jsonb_build_object('id',p.id,'username',p.username,
        'player_id',(SELECT id FROM public.player WHERE profile_id=p.id),'needs_profile',false)
        INTO identity FROM public.profile p WHERE p.id=p_actor;
    RETURN identity || soe_private.permission_data(p_actor);
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_admin_users(p_actor uuid,p_query text DEFAULT '',p_limit integer DEFAULT 30,p_offset integer DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE result jsonb;
BEGIN
    PERFORM soe_private.authorize(p_actor,NULL,true);
    SELECT jsonb_build_object('total',(SELECT count(*) FROM public.profile WHERE username ILIKE '%'||left(coalesce(p_query,''),80)||'%'),
        'items',coalesce((SELECT jsonb_agg(item ORDER BY username,id) FROM (
            SELECT id,username,jsonb_build_object('id',id,'username',username,'status',status)
                || soe_private.permission_data(id) AS item
            FROM public.profile WHERE username ILIKE '%'||left(coalesce(p_query,''),80)||'%'
            ORDER BY username,id LIMIT least(greatest(p_limit,1),100) OFFSET greatest(p_offset,0)
        ) profiles),'[]'::jsonb)) INTO result;
    RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_set_moderator(p_actor uuid,p_target uuid,p_community bigint,p_enabled boolean,p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE was_assigned boolean;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended('soe/permissions',0));
    PERFORM soe_private.authorize(p_actor,NULL,true);
    IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 10 AND 2000 OR p_enabled IS NULL THEN
        RAISE EXCEPTION 'SOE_REASON_REQUIRED' USING ERRCODE='22023';
    END IF;
    IF p_enabled THEN PERFORM soe_private.assert_actor(p_target); END IF;
    IF NOT EXISTS(SELECT 1 FROM public.profile WHERE id=p_target)
        OR NOT EXISTS(SELECT 1 FROM public.community WHERE id=p_community) THEN
        RAISE EXCEPTION 'SOE_INVALID_REFERENCE' USING ERRCODE='22023';
    END IF;
    SELECT EXISTS(SELECT 1 FROM soe_private.community_moderator
        WHERE profile_id=p_target AND community_id=p_community) INTO was_assigned;
    IF p_enabled=was_assigned THEN
        RETURN soe_private.permission_data(p_target) || jsonb_build_object('changed',false);
    END IF;
    IF p_enabled THEN
        INSERT INTO soe_private.community_moderator(profile_id,community_id,assigned_by)
        VALUES(p_target,p_community,p_actor);
    ELSE
        DELETE FROM soe_private.community_moderator WHERE profile_id=p_target AND community_id=p_community;
    END IF;
    INSERT INTO soe_private.security_audit(actor_profile_id,action,target_profile_id,community_id,previous_value,next_value,reason)
    VALUES(p_actor,CASE WHEN p_enabled THEN 'MODERATOR_GRANTED' ELSE 'MODERATOR_REVOKED' END,p_target,p_community,
        jsonb_build_object('assigned',was_assigned),jsonb_build_object('assigned',p_enabled),btrim(p_reason));
    RETURN soe_private.permission_data(p_target) || jsonb_build_object('changed',true);
END;
$$;

CREATE OR REPLACE FUNCTION soe_private.match_review(p_actor uuid,p_match bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
SELECT jsonb_build_object('id',m.id,'community_id',m.community_id,'format_id',m.format_id,
    'format_name',f.name,'match_date',m.match_date,'approximate_start_time',m.approximate_start_time,
    'status',m.status,'author',p.username,'dispute_reason',NULL,
    'self_involved',coalesce(m.created_by=p_actor,false) OR EXISTS(SELECT 1 FROM public.match_participant mp
        JOIN public.player pl ON pl.id=mp.player_id WHERE mp.match_id=m.id AND pl.profile_id=p_actor),
    'participants',coalesce((SELECT jsonb_agg(jsonb_build_object('player_id',pl.id,
        'display_name',pl.display_name,'is_guest',pl.profile_id IS NULL,'result',mp.result) ORDER BY mp.id)
        FROM public.match_participant mp JOIN public.player pl ON pl.id=mp.player_id WHERE mp.match_id=m.id),'[]'::jsonb),
    'resolution_history',coalesce((SELECT jsonb_agg(jsonb_build_object('id',a.id,
        'actor',ap.username,'actor_id',a.actor_profile_id,'occurred_at',a.occurred_at,'reason',a.reason,
        'previous',a.previous_value,'next',a.next_value) ORDER BY a.id)
        FROM soe_private.security_audit a LEFT JOIN public.profile ap ON ap.id=a.actor_profile_id
        WHERE a.match_id=m.id AND a.action='DISPUTE_RESOLVED'),'[]'::jsonb))
FROM public.game_match m JOIN public.format f ON f.id=m.format_id
LEFT JOIN public.profile p ON p.id=m.created_by WHERE m.id=p_match;
$$;

CREATE OR REPLACE FUNCTION public.soe_moderation_matches(p_actor uuid,p_community bigint DEFAULT NULL,p_limit integer DEFAULT 30,p_offset integer DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE ids bigint[]; result jsonb;
BEGIN
    PERFORM soe_private.authorize(p_actor,p_community);
    IF EXISTS(SELECT 1 FROM soe_private.platform_admin WHERE profile_id=p_actor) THEN
        SELECT array_agg(id) INTO ids FROM public.community;
    ELSE
        SELECT array_agg(community_id) INTO ids FROM soe_private.community_moderator WHERE profile_id=p_actor;
    END IF;
    SELECT jsonb_build_object('total',(SELECT count(*) FROM public.game_match
        WHERE status='DISPUTED' AND community_id=ANY(ids) AND (p_community IS NULL OR community_id=p_community)),
        'items',coalesce((SELECT jsonb_agg(soe_private.match_review(p_actor,id) ORDER BY id) FROM (
            SELECT id FROM public.game_match WHERE status='DISPUTED' AND community_id=ANY(ids)
                AND (p_community IS NULL OR community_id=p_community)
            ORDER BY id LIMIT least(greatest(p_limit,1),100) OFFSET greatest(p_offset,0)
        ) matches),'[]'::jsonb)) INTO result;
    RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_moderation_match(p_actor uuid,p_match bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE community bigint;
BEGIN
    PERFORM soe_private.authorize(p_actor);
    SELECT community_id INTO community FROM public.game_match WHERE id=p_match;
    IF NOT FOUND THEN RAISE EXCEPTION 'SOE_ACCESS_DENIED' USING ERRCODE='42501'; END IF;
    PERFORM soe_private.authorize(p_actor,community);
    RETURN soe_private.match_review(p_actor,p_match);
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_resolve_dispute(p_actor uuid,p_match bigint,p_decision text,p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE m public.game_match%ROWTYPE; new_status text; snapshot jsonb;
BEGIN
    PERFORM soe_private.authorize(p_actor);
    -- Mesmo lock de partida que serializa alterações de participantes na migração 002.
    SELECT * INTO m FROM public.game_match WHERE id=p_match FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'SOE_ACCESS_DENIED' USING ERRCODE='42501'; END IF;
    PERFORM soe_private.authorize(p_actor,m.community_id);
    IF m.created_by=p_actor OR EXISTS(SELECT 1 FROM public.match_participant mp
        JOIN public.player pl ON pl.id=mp.player_id WHERE mp.match_id=m.id AND pl.profile_id=p_actor) THEN
        RAISE EXCEPTION 'SOE_SELF_REVIEW' USING ERRCODE='42501';
    END IF;
    IF m.status<>'DISPUTED' THEN RAISE EXCEPTION 'SOE_DISPUTE_CHANGED' USING ERRCODE='40001'; END IF;
    IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 10 AND 2000 THEN
        RAISE EXCEPTION 'SOE_REASON_REQUIRED' USING ERRCODE='22023';
    END IF;
    IF p_decision IS NULL OR p_decision NOT IN ('VERIFY','CANCEL') THEN
        RAISE EXCEPTION 'SOE_INVALID_DECISION' USING ERRCODE='22023';
    END IF;
    IF p_decision='VERIFY' THEN PERFORM soe_private.assert_result(m.id); END IF;
    new_status:=CASE WHEN p_decision='VERIFY' THEN 'VERIFIED' ELSE 'CANCELLED' END;
    SELECT jsonb_build_object('status',m.status,'match_date',m.match_date,'start',m.approximate_start_time,
        'format_id',m.format_id,'participants',jsonb_agg(jsonb_build_object('player_id',player_id,'result',result) ORDER BY player_id))
        INTO snapshot FROM public.match_participant WHERE match_id=m.id;
    UPDATE public.game_match SET status=new_status,updated_at=clock_timestamp() WHERE id=m.id;
    INSERT INTO soe_private.security_audit(actor_profile_id,action,community_id,match_id,previous_value,next_value,reason)
    VALUES(p_actor,'DISPUTE_RESOLVED',m.community_id,m.id,snapshot,
        jsonb_build_object('status',new_status,'decision',p_decision),btrim(p_reason));
    RETURN soe_private.match_review(p_actor,m.id);
END;
$$;

CREATE OR REPLACE FUNCTION public.soe_admin_audit(p_actor uuid,p_limit integer DEFAULT 30,p_offset integer DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    PERFORM soe_private.authorize(p_actor,NULL,true);
    RETURN jsonb_build_object('total',(SELECT count(*) FROM soe_private.security_audit),
        'items',coalesce((SELECT jsonb_agg(item ORDER BY id DESC) FROM (
            SELECT a.id,jsonb_build_object('id',a.id,'actor',p.username,'actor_id',a.actor_profile_id,
                'database_actor',a.database_actor,'action',a.action,'target_profile_id',a.target_profile_id,
                'community_id',a.community_id,'match_id',a.match_id,'previous',a.previous_value,
                'next',a.next_value,'reason',a.reason,'occurred_at',a.occurred_at) AS item
            FROM soe_private.security_audit a LEFT JOIN public.profile p ON p.id=a.actor_profile_id
            ORDER BY a.id DESC LIMIT least(greatest(p_limit,1),100) OFFSET greatest(p_offset,0)
        ) events),'[]'::jsonb));
END;
$$;

-- Operador do banco somente: não há endpoint HTTP nem EXECUTE para service_role.
CREATE OR REPLACE FUNCTION soe_private.manage_admin(p_target uuid,p_enabled boolean,p_reason text,p_bootstrap boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE was_admin boolean; admin_count integer;
BEGIN
    IF current_setting('transaction_isolation') <> 'read committed' THEN
        RAISE EXCEPTION 'SOE_RETRY_TRANSACTION' USING ERRCODE='40001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('soe/permissions',0));
    IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 10 AND 2000
        OR p_enabled IS NULL OR p_bootstrap IS NULL THEN
        RAISE EXCEPTION 'SOE_REASON_REQUIRED' USING ERRCODE='22023';
    END IF;
    SELECT count(*) INTO admin_count FROM soe_private.platform_admin;
    IF (p_bootstrap AND (admin_count<>0 OR NOT p_enabled)) OR (NOT p_bootstrap AND admin_count=0) THEN
        RAISE EXCEPTION 'SOE_BOOTSTRAP_STATE' USING ERRCODE='42501';
    END IF;
    IF p_enabled THEN
        PERFORM soe_private.assert_actor(p_target);
    ELSIF NOT EXISTS(SELECT 1 FROM public.profile WHERE id=p_target) THEN
        RAISE EXCEPTION 'SOE_INVALID_REFERENCE' USING ERRCODE='22023';
    END IF;
    SELECT EXISTS(SELECT 1 FROM soe_private.platform_admin WHERE profile_id=p_target) INTO was_admin;
    IF was_admin=p_enabled THEN RETURN jsonb_build_object('changed',false); END IF;
    IF NOT p_enabled AND admin_count=1 THEN
        RAISE EXCEPTION 'SOE_LAST_ADMIN' USING ERRCODE='42501';
    END IF;
    IF p_enabled THEN INSERT INTO soe_private.platform_admin(profile_id) VALUES(p_target);
    ELSE DELETE FROM soe_private.platform_admin WHERE profile_id=p_target; END IF;
    INSERT INTO soe_private.security_audit(action,target_profile_id,previous_value,next_value,reason)
    VALUES(CASE WHEN p_bootstrap THEN 'BOOTSTRAP_ADMIN' WHEN p_enabled THEN 'ADMIN_GRANTED' ELSE 'ADMIN_REVOKED' END,
        p_target,jsonb_build_object('admin',was_admin),jsonb_build_object('admin',p_enabled),btrim(p_reason));
    RETURN jsonb_build_object('changed',true) || soe_private.permission_data(p_target);
END;
$$;

